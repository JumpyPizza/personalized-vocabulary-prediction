prompt = """
You are given a small labeled sample of vocabulary words that indicate a second-language English learner's knowledge of these words.
If the learner definitely knows the word, the label is 5; 
If the learner knows the word but is less confident, the label is 4;
If the learner sees the word before but could not think of its meaning, the label is 3;
If the learner is not sure if he sees the word before, the label is 2;
If the learer definitely does not know the word, the labels is 1;
The samples are: {samples}
Your goal is to analyze this small set and to infer the user's vocabulary knowledge characteristics.
Identify the pattern, do not explicitly express the user's vocabulary knowledge profile. 
Focus on reasoning and inferring the user's knowledge about the following word: {word_to_pred}, to give a binary label for this word: 1 means knows the word and 0 means does not know the word. 
Place your reasoning between <think> and </think>, then put your final answer within \\boxed{{}}.
"""

prompt_binary = """
You are given a small labeled sample of vocabulary words that indicate a second-language English learner's knowledge of these words.
If the learner knows the word, the label is 5; If the learer does not know the word, the labels is 1.
Your goal is to analyze this small set, identify the internal pattern, and infer the user's vocabulary knowledge characteristics.
Then, predict a binary label for any given word: 1 means knows the word and 0 means does not know the word. 
You should directly return your inference in the json format, e.g.,{{"word_0": "1", "word_1": "1", "word_2": "1", ...}}.
The samples are: {samples};
Infer the user's knowledge about the following words: {word_to_pred}. 
"""


def get_data_from_json(json_data, sample_size = 50):
    # sample_size: how many samples (words) one initial_words contains
    # this function composes dataset from error data, which is generated by get_samples.py
    if not json_data.get("initial_samples") or not json_data.get("errors"):
        raise RuntimeError("No data")
    
    data_entry = []
    for list_of_word in json_data['initial_samples']:
        word = list_of_word[0]
        labels = list_of_word[1]
        initial_words_string = ""
        for w, l in zip(word, labels):
            initial_words_string += f"{w}: {l}; "
        error_samples = random.sample(json_data["errors"], sample_size)
        for i in range(0, sample_size):
            pred_sample = error_samples[i] # true, pred, prob
            
            
            for pred_word, v in pred_sample.items():
                ground_truth = v[0]
                prompt_string = prompt.format(samples = initial_words_string, word_to_pred = pred_word)
                data = {
                    "prompt":prompt_string,
                    "ground_truth" : ground_truth
                } 
                data_entry.append(data)

    return data_entry 

def get_data_from_user_data(user_data, tokenizer,
                             initial_sample_num = 30, N_query_words = 10, 
                             n_each_task = 100,
                             n_task = 10):
    # this function randomly sample initial_sample_num words as the initial samples, which is the meta_train_data
    # then randomly sample N words as the query words
    # n_task control how many different sets of initial words are sampled 
    # n_each task control how many prompts (each containing n_task query words) are sampled for a single set of initial words 
    # Return: the task sampled from a single user 
    user_oracle = UserSimulationOracle(user_data=user_data, tokenizer=tokenizer, initial_sample_num=initial_sample_num)
    data_entry = []
    for i in range(n_task):
        initial_words = user_oracle.query_initial_samples()
        initial_words_string = ""
        
        for w, l in zip(initial_words[0], initial_words[1]) :
        
            initial_words_string += f"{w}: {l}; "
        for j in range(n_each_task):
            query_words = user_oracle.query_initial_samples(sample_num = N_query_words)
            query_words_string = "["
            for w in query_words[0]:
                query_words_string += f"{w}, "
            query_words_string += "]"
            prompt_string = prompt_binary.format(samples = initial_words_string, word_to_pred = query_words_string)
            ground_truth = {w: str(l) for w, l in zip(query_words[0], query_words[1])}
            gt = json.dumps(ground_truth)
            data = {
                "prompt": [
                    {"role": "user", "content": prompt_string} 
                ],
                "completion": [
                    {"role": "assistant", "content": gt} 
                ],
            }
            data_entry.append(data)
    return data_entry


